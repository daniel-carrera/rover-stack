#include "src/clock.hpp"

// The handler builds the command, stamps it, calls admit for the verdict, answers the request
// if the command is accepted, it the command is added to the loop's slot under a lock
// each tick, the loop takes whatever is in the slot, could be nothing, and the time now
// the guard processes tick and does the second "admit" itself and returns a TickOutput: command to write, 
// if its a repeat command (for logging), if its a lapse and how many stops to send if any
// the loop then builds the frame based on the TickOutput and sends that to the port.
// That explains why tick requires a now and an optional command

// Now before the stamp: The core loop handles a steady clock, which never runs backwards
// the fake clock in the tests only runs forwards.
// A negative difference between stamp and now cannot happen, if it did the lease comparison would read as fresh.

// command created by the loop, passed to guard
// x, y are stick direction components
// press_id is generated by the page, passed as string, just checked for equality, never inspected
// is_stop flags command as a stop command
struct Command{
    double x;
    double y;
    std::optional<std::string> press_id;
    bool is_stop;
    std::uint64_t sender_start;
    std::uint64_t sender_counter;
};

// admit return type, see admit function comment
enum class Verdict { 
    refused_range,
    refused_out_of_order,
    refused_stale,
    refused_spent_press,
    refused_not_centered,
    accepted
};

// Kinds of tick output result, processed by loop
// This is a design choice, and the core loop needs to interpret and decide how to handle each of these cases
enum class TickOutputType {
    regular_command, // new command, new frame to send
    repeat_command, // repeated command, same frame as before
    stop_command, // explicit stop request, with no lapse
    lapse, // lease lapsed
    latched_burst, // repeated burst while latched
    latched_stop // tick while latched
};

// command is a full copy, string included, can be optimized for later
struct TickOutput{
    Command command;
    TickOutputType kind;
};

class Guard {
public:
    Guard(
        Duration lease
    ): lease_(lease){}

    // returns Verdict
    // checks:
    //  sticks are in range, if not or invalid number, refused range
    //  stale: now minus timestamp is at or over lease, refused stale.
    //         the stale rule applies to the live press only, and a fresh press is 
    //         judged by range, spent and centred. The core needs no extra state for that.
    //  spent press: press id already ended: refused spent press
    //  new press while latched: accepted only if stick centered, else refused not centered
    //  else: accepted
    Verdict admit(Command command, Time now) const;
    
    // Processes one tick:
    // Command waiting: runs admit with command and now.
        // if command accepted: send it back, update current command, timestamp
        // if refused: update TickOutput as necessary with appropriate TickOutputType kind
    TickOutput tick(std::optional<Command> command, Time now);


private: 
    // latch, burst time, zero sticks, is_stop, insert spent press
    // used for lapse and explicit stop
    void end_press(Time now);

    Duration lease_;

    Command current_command_ = {
        .x = 0.0,
        .y = 0.0,
        .press_id = std::nullopt, // the empty press id is the “no live press” marker
        .is_stop = true,
        .sender_start = 0,
        .sender_counter = 0
    };
    Time command_time_stamp_ = Time{};
    // the latched branch bursts when there is 
    std::optional<Time> last_burst_time_stamp_ = std::nullopt; 
    // no last burst (on startup), or a whole lease has passed since. 
    std::unordered_set<std::string> spent_press_ids_;
    bool latched_ = true;
    // a stop, lapse and a takeover fill it too, and it holds the press that was being driven
    std::optional<std::string> spent_press_;
    std::uint64_t sender_start_ = 0;
    std::uint64_t sender_counter_ = 0;
    
    // inclusive to the value is valid
    double center_band_ = 0.1; 
    double max_stick_value_ = 1.0;
    double min_stick_value_ = -1.0;
    // std::uint64_t min_press_id_length_ = 1;
    // std::uint64_t max_press_id_length_ = 64;
};